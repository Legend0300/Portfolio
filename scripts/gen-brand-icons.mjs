// Generates lib/brand-icons.js from the simple-icons package (CC0). Run: node scripts/gen-brand-icons.mjs
import * as si from "simple-icons";
import { writeFileSync } from "node:fs";

const wanted = {
  github: "siGithub", githubactions: "siGithubactions", terraform: "siTerraform", kubernetes: "siKubernetes",
  docker: "siDocker", cloudflare: "siCloudflare", workers: "siCloudflareworkers", go: "siGo", python: "siPython",
  typescript: "siTypescript", cpp: "siCplusplus", redis: "siRedis", postgresql: "siPostgresql", nextjs: "siNextdotjs",
  react: "siReact", openai: "siOpenai", fastapi: "siFastapi", celery: "siCelery", prometheus: "siPrometheus",
  grafana: "siGrafana", nginx: "siNginx", pytest: "siPytest", ansible: "siAnsible", jenkins: "siJenkins",
  hono: "siHono", playwright: "siPlaywright", electron: "siElectron", flask: "siFlask", linux: "siLinux",
  helm: "siHelm", trivy: "siTrivy", githubcopilot: "siGithubcopilot", sqlite: "siSqlite", tailwind: "siTailwindcss",
};
const out = {};
const missing = [];
for (const [key, exp] of Object.entries(wanted)) {
  const icon = si[exp];
  if (!icon) { missing.push(key); continue; }
  out[key] = { title: icon.title, hex: icon.hex, path: icon.path };
}
writeFileSync(new URL("../lib/brand-icons.js", import.meta.url), `// Generated by scripts/gen-brand-icons.mjs from simple-icons (CC0). Brand marks belong to their owners.\nexport const brandIcons = ${JSON.stringify(out, null, 1)};\n`);
console.log("wrote", Object.keys(out).length, "icons; missing:", missing.join(", ") || "none");
